-- F5a: additive PDF foundation. Existing course/market gates and completion remain unchanged.
create table if not exists public.pdf_documents (
 id uuid primary key default gen_random_uuid(),
 weekly_update_id bigint references public.weekly_updates(id) on delete restrict,
 module_id bigint references public.modules(id) on delete restrict,
 title text not null check(length(title) between 1 and 160),
 object_path text not null unique,
 byte_size integer not null check(byte_size between 1 and 3145728),
 page_count integer not null check(page_count between 1 and 150),
 sha256 text not null check(sha256 ~ '^[a-f0-9]{64}$'),
 version uuid not null default gen_random_uuid(),
 state text not null default 'draft' check(state in ('draft','ready','deleting','error')),
 storage_ready boolean not null default false,
 accessible_html text not null default '' check(length(accessible_html)<=100000),
 accessible_verified boolean not null default false,
 error_message text,
 created_by uuid references public.students(id) on delete set null,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 check(num_nonnulls(weekly_update_id,module_id)=1),
 check(object_path='documents/'||id::text||'/source.pdf'),
 check(state<>'ready' or (storage_ready and accessible_verified and length(accessible_html)>20))
);
alter table public.pdf_documents enable row level security;
revoke all on public.pdf_documents from public,anon,authenticated;
grant all on public.pdf_documents to service_role;

create or replace function public.can_read_pdf(p_document_id uuid)
returns boolean language plpgsql stable security definer set search_path='' as $$
declare d public.pdf_documents; v_student public.students;
begin
 select * into v_student from public.students where auth_user_id=auth.uid();
 if v_student.id is null or not exists(select 1 from auth.users where id=auth.uid()) then return false; end if;
 select * into d from public.pdf_documents where id=p_document_id;
 if d.id is null then return false; end if;
 if v_student.access_level=3 then return d.storage_ready and d.state in ('draft','ready'); end if;
 if d.state<>'ready' or not d.storage_ready then return false; end if;
 if d.weekly_update_id is not null then return public.can_read_market_post(d.weekly_update_id); end if;
 -- Full module entitlement; deliberately excludes the first-lesson preview shortcut.
 return public.can_open_academy_module(d.module_id);
end;$$;
revoke all on function public.can_read_pdf(uuid) from public,anon;
grant execute on function public.can_read_pdf(uuid) to authenticated;

create or replace function public.is_pdf_admin()
returns boolean language sql stable security definer set search_path='' as $$
 select public.is_platform_admin() and exists(select 1 from auth.users where id=auth.uid());
$$;
revoke all on function public.is_pdf_admin() from public,anon;
grant execute on function public.is_pdf_admin() to authenticated;

create table if not exists public.pdf_open_logs (
 id bigint generated by default as identity primary key,
 document_id uuid not null,
 document_version uuid not null,
 document_title text not null,
 weekly_update_id bigint,
 module_id bigint,
 student_id uuid not null references public.students(id) on delete cascade,
 request_id uuid not null,
 opened_at timestamptz not null default now(),
 unique(student_id,document_id,request_id)
);
create index if not exists pdf_open_logs_retention on public.pdf_open_logs(opened_at);
alter table public.pdf_open_logs enable row level security;
revoke all on public.pdf_open_logs from public,anon,authenticated;
grant select on public.pdf_open_logs to authenticated;
grant all on public.pdf_open_logs to service_role;
drop policy if exists pdf_open_logs_admin on public.pdf_open_logs;
create policy pdf_open_logs_admin on public.pdf_open_logs for select to authenticated using (
 public.is_pdf_admin() and opened_at>=now()-interval '30 days'
);

create or replace function public.record_pdf_open(p_document_id uuid,p_version uuid,p_request_id uuid,p_student_id uuid)
returns void language plpgsql security definer set search_path='' as $$
declare d public.pdf_documents; v_auth uuid; v_claims text; v_sub text;
begin
 select auth_user_id into v_auth from public.students where id=p_student_id;
 if v_auth is null or p_request_id is null or not exists(select 1 from auth.users where id=v_auth) then raise exception 'PDF access denied' using errcode='42501'; end if;
 perform 1 from auth.users where id=v_auth for key share;
 if not found then raise exception 'PDF access denied' using errcode='42501'; end if;
 -- Only the trusted server can record a successful transformation. Reuse the live
 -- user gate instead of duplicating subscription/intake/legacy business rules.
 v_claims:=current_setting('request.jwt.claims',true);v_sub:=current_setting('request.jwt.claim.sub',true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',v_auth,'role','authenticated')::text,true);
 perform set_config('request.jwt.claim.sub',v_auth::text,true);
 if not public.can_read_pdf(p_document_id) then raise exception 'PDF access denied' using errcode='42501'; end if;
 select * into d from public.pdf_documents where id=p_document_id for share;
 if d.version is distinct from p_version then raise exception 'PDF version changed' using errcode='22023'; end if;
 perform set_config('request.jwt.claims',coalesce(v_claims,''),true);perform set_config('request.jwt.claim.sub',coalesce(v_sub,''),true);
 insert into public.pdf_open_logs(document_id,document_version,document_title,weekly_update_id,module_id,student_id,request_id)
 values(d.id,d.version,d.title,d.weekly_update_id,d.module_id,p_student_id,p_request_id)
 on conflict(student_id,document_id,request_id) do nothing;
end;$$;
revoke all on function public.record_pdf_open(uuid,uuid,uuid,uuid) from public,anon,authenticated;
grant execute on function public.record_pdf_open(uuid,uuid,uuid,uuid) to service_role;

create or replace function public.purge_pdf_open_logs()
returns bigint language plpgsql security definer set search_path='' as $$
declare n bigint;begin
 delete from public.pdf_open_logs where opened_at<now()-interval '30 days';get diagnostics n=row_count;return n;
end;$$;
revoke all on function public.purge_pdf_open_logs() from public,anon,authenticated;
grant execute on function public.purge_pdf_open_logs() to service_role;
create extension if not exists pg_cron with schema pg_catalog;
select cron.schedule('htp-pdf-open-log-retention','* * * * *','select public.purge_pdf_open_logs();');

create or replace function public.cleanup_deleted_auth_pdf_logs() returns trigger
language plpgsql security definer set search_path='' as $$begin
 delete from public.pdf_open_logs l using public.students s where l.student_id=s.id and s.auth_user_id=old.id;return old;
end;$$;
revoke all on function public.cleanup_deleted_auth_pdf_logs() from public,anon,authenticated;
drop trigger if exists cleanup_deleted_auth_pdf_logs on auth.users;
create trigger cleanup_deleted_auth_pdf_logs before delete on auth.users for each row execute function public.cleanup_deleted_auth_pdf_logs();

